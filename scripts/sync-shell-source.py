#!/usr/bin/env python3
"""Copy the canonical compiler into the independently installable runner.

Run from any directory. --check is read-only and fails on missing, changed, or
stale generated Python files. The mirror has no independent implementation.
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path("modules/tool-recipes/amplifier_module_tool_recipes/shell_source")
MIRROR = Path("src/amplifier_recipe_runner/_shell_source")
HEADER = b"# Generated by scripts/sync-shell-source.py; edit the canonical shell_source package.\n"


def mirror_changes(root: Path) -> dict[Path, bytes | None]:
    """Return deterministic writes/deletions, confined to generated Python files."""
    source, mirror = root / SOURCE, root / MIRROR
    files = sorted(source.rglob("*.py"))
    if not files or not (source / "__init__.py").is_file():
        raise ValueError("Canonical shell_source package is missing")
    expected = {p.relative_to(source): HEADER + p.read_bytes() for p in files}
    changes = {
        relative: data
        for relative, data in expected.items()
        if not (mirror / relative).is_file() or (mirror / relative).read_bytes() != data
    }
    for stale in sorted(mirror.rglob("*.py")):
        relative = stale.relative_to(mirror)
        if relative not in expected:
            changes[relative] = None
    return changes


def synchronize(root: Path, *, check: bool = False) -> list[str]:
    changes = mirror_changes(root)
    if not check:
        for relative, content in changes.items():
            path = root / MIRROR / relative
            if content is None:
                path.unlink()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content)
    return [str(path) for path in sorted(changes)]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changes = synchronize(ROOT, check=args.check)
    if changes:
        print(("Stale shell-source mirror: " if args.check else "Updated shell-source mirror: ") + ", ".join(changes))
    return int(args.check and bool(changes))


if __name__ == "__main__":
    raise SystemExit(main())
